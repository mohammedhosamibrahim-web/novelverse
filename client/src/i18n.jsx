const dictionaries = { en, ar };
const TITLES = {
  en: 'NovelVerse — Manga & Novels',
  ar: 'نوفل فيرس — مانجا وروايات',
};

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      const saved = localStorage.getItem('lang');
      if (saved === 'en' || saved === 'ar') return saved;
    } catch {
      /* ignore */
    }
    return typeof navigator !== 'undefined' && navigator.language && navigator.language.toLowerCase().startsWith('ar') ? 'ar' : 'en';
  });

  useEffect(() => {
    const dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.setAttribute('dir', dir);
    document.documentElement.setAttribute('lang', lang);
    document.title = TITLES[lang] || TITLES.en;
    try {
      localStorage.setItem('lang', lang);
    } catch {
      /* ignore */
    }
  }, [lang]);

  const setLang = useCallback((code) => {
    if (code === 'en' || code === 'ar') setLangState(code);
  }, []);

  const t = useCallback(
    (key, vars) => {
      let str = (dictionaries[lang] && dictionaries[lang][key]) || dictionaries.en[key] || key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
        }
      }
      return str;
    },
    [lang]
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  return useContext(LanguageContext);
}
